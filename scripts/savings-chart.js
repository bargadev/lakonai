'use strict';

// Renders the README savings chart from a fresh e2e run:
//   docs/assets/savings-e2e.svg  — horizontal bars, % smaller per command
//   docs/benchmark-e2e.md        — the same numbers as a table
// Run: npm run bench:e2e

const fs = require('fs');
const path = require('path');
const { runAll } = require('./savings-e2e');

const ROOT = path.join(__dirname, '..');
const VERSION = require('../package.json').version;

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const num = (n) => n.toLocaleString('en-US');

// Bar with a 4px rounded data end, square at the baseline.
function barPath(x, y, w, h, r = 4) {
  if (w <= 0) return '';
  const rr = Math.min(r, w, h / 2);
  return `M${x},${y}H${x + w - rr}Q${x + w},${y} ${x + w},${y + rr}V${y + h - rr}Q${x + w},${y + h} ${x + w - rr},${y + h}H${x}Z`;
}

function renderSvg(rows, { total }) {
  const W = 820;
  const labelW = 250;
  const plotW = 340;
  const rowH = 34;
  const barH = 18;
  const top = 78;
  const H = top + rows.length * rowH + 40;
  const x0 = labelW;
  const xs = (pct) => x0 + (Math.max(0, pct) / 100) * plotW;

  const grid = [0, 25, 50, 75, 100]
    .map((p) => `<line class="grid" x1="${xs(p)}" x2="${xs(p)}" y1="${top - 8}" y2="${top + rows.length * rowH - 6}"/>` +
      `<text class="axis" x="${xs(p)}" y="${top + rows.length * rowH + 12}" text-anchor="middle">${p}%</text>`)
    .join('');

  const bars = rows.map((r, i) => {
    const y = top + i * rowH;
    const tip = xs(r.saved);
    const d = barPath(x0, y, tip - x0, barH);
    return `<g><title>${esc(r.label)}: ${num(r.rawTok)} → ${num(r.outTok)} tokens (${r.saved}% smaller)</title>` +
      `<text class="label" x="${labelW - 14}" y="${y + barH / 2 + 4.5}" text-anchor="end">${esc(r.label)}</text>` +
      (d ? `<path class="bar" d="${d}"/>` : '') +
      `<text class="value" x="${tip + 8}" y="${y + barH / 2 + 4.5}">${r.saved}%` +
      `<tspan class="muted" dx="8">${num(r.rawTok)} → ${num(r.outTok)}</tspan></text></g>`;
  }).join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t d">
<title id="t">lakonai: tokens saved per command</title>
<desc id="d">End-to-end run of real commands on a fixture git repository, raw output versus lakonai output. Overall ${total.saved}% smaller (${num(total.raw)} → ${num(total.out)} tokens).</desc>
<style>
  :root { --surface: #fcfcfb; --ink: #0b0b0b; --ink-2: #52514e; --ink-3: #8a8983; --grid: #e6e5e0; --series-1: #2a78d6; }
  @media (prefers-color-scheme: dark) {
    :root { --surface: #1a1a19; --ink: #f0efec; --ink-2: #c3c2b7; --ink-3: #8f8e86; --grid: #2e2e2c; --series-1: #3987e5; }
  }
  text { font-family: ui-sans-serif, -apple-system, "Segoe UI", Roboto, sans-serif; fill: var(--ink); }
  .bg { fill: var(--surface); }
  .h1 { font-size: 17px; font-weight: 600; }
  .sub { font-size: 12.5px; fill: var(--ink-2); }
  .label { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 12.5px; fill: var(--ink); }
  .value { font-size: 12.5px; font-weight: 600; fill: var(--ink); }
  .muted { font-weight: 400; fill: var(--ink-2); }
  .axis { font-size: 11px; fill: var(--ink-3); }
  .grid { stroke: var(--grid); stroke-width: 1; }
  .bar { fill: var(--series-1); }
</style>
<rect class="bg" width="${W}" height="${H}" rx="8"/>
<text class="h1" x="24" y="32">Tokens saved per command: ${total.saved}% overall</text>
<text class="sub" x="24" y="52">Real CLI runs on a fixture repo (61 files, 31 commits) · raw → lakonai tokens (≈4 chars/token) · v${esc(VERSION)}</text>
${grid}
${bars}
</svg>
`;
}

function renderTable(rows, { total }) {
  const lines = [
    '| Command | Raw | lakonai | Smaller |',
    '|---|---:|---:|---:|',
    ...rows.map((r) => `| \`${r.label.replace(/\|/g, '\\|')}\` | ${num(r.rawTok)} | ${num(r.outTok)} | **${r.saved}%** |`),
    `| **Total** | **${num(total.raw)}** | **${num(total.out)}** | **${total.saved}%** |`,
  ];
  return lines.join('\n');
}

function main() {
  const rows = runAll().sort((a, b) => b.saved - a.saved);
  const raw = rows.reduce((a, r) => a + r.rawTok, 0);
  const out = rows.reduce((a, r) => a + r.outTok, 0);
  const total = { raw, out, saved: Math.round((1 - out / raw) * 1000) / 10 };
  const bad = rows.filter((r) => r.missing.length);
  if (bad.length) throw new Error(`signal lost: ${bad.map((r) => `${r.label} (${r.missing.join(', ')})`).join('; ')}`);

  fs.mkdirSync(path.join(ROOT, 'docs', 'assets'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs', 'assets', 'savings-e2e.svg'), renderSvg(rows, { total }));
  const md = `# End-to-end savings (v${VERSION})

Generated by \`npm run bench:e2e\` (scripts/savings-chart.js) from the same run
that \`tests/savings-e2e.test.js\` asserts on: a deterministic git repository is
built on disk, each command runs once raw and once through the real CLI (or the
real PreToolUse hook + \`sh\` for the \`cd … &&\` row), and every row also checks
that the lines that matter survived (latest commit subject, changed lines, the
build warning, …). Tokens are estimated at ~4 characters per token.

${renderTable(rows, { total })}

Reads (\`sed -n\`, \`cat\`) are file content the agent asked for: lakonai
leaves them nearly untouched on purpose.
`;
  fs.writeFileSync(path.join(ROOT, 'docs', 'benchmark-e2e.md'), md);
  process.stdout.write(renderTable(rows, { total }) + '\n');
}

module.exports = { renderSvg, renderTable, barPath };

if (require.main === module) main();
